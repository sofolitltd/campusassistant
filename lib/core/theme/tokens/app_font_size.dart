/// Font size scale for the Campus Assistant design system.
///
/// Usage: `TextStyle(fontSize: FontSizeToken.base)`
abstract final class FontSizeToken {
  static const double xxs = 10; // micro labels, badges
  static const double xs = 11; // captions
  static const double sm = 12; // secondary text, chips
  static const double md = 13; // dense body text
  static const double base = 14; // default body text
  static const double lg = 16; // buttons, emphasized body
  static const double xl = 18; // card and section titles
  static const double xxl = 20; // page titles
  static const double display = 24; // hero numbers and headings
}
